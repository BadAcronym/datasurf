#include "datasurf_main.h"
#include "pd_print_macros.h"

int main
(
    void
){
    uint8_t failed = 0;
    uint8_t uncompressed[46] =
    {
        //zlib header
        0x78, 0x01,
        // deflate stream
        0x01, 0x22, 0x00, 0xDD, 0xFF, 0x48, 0x65,
        0x6C, 0x6C, 0x6F, 0x20, 0x77, 0x6F, 0x72,
        0x6C, 0x64, 0x2C, 0x20, 0x74, 0x68, 0x69,
        0x73, 0x20, 0x69, 0x73, 0x20, 0x75, 0x6E,
        0x63, 0x6F, 0x6D, 0x70, 0x72, 0x65, 0x73,
        0x73, 0x65, 0x64, 0x2E,
        // ADLER-32 checksum of uncompressed data
        0xDA, 0x3D, 0x0C, 0xA3
    };
    uint8_t testUncompressed[39] = {0};

    if(!dsReadZlibPtr(uncompressed, testUncompressed))
    {
        PD_FAIL("dsReadZlibPtr: could not read uncompressed string.");
        ++failed;
    }
    else
    {
        PD_SUCCESS("passed dsReadZlibPtr with uncompressed zlib string.");
    }

    uint8_t fastCompressed[70] =
    {
        // zlib header
        0x78, 0x5E,
        // deflate stream
        0xF3, 0x48, 0xCD, 0xC9, 0xC9, 0x57, 0xC8, 0x00, 0x91, 0x3A,
        0x0A, 0x25, 0x19, 0x99, 0xC5, 0x0A, 0x40, 0x94, 0x9C, 0x9F,
        0x5B, 0x50, 0x94, 0x5A, 0x5C, 0x9C, 0x99, 0x9F, 0xA7, 0x90,
        0x98, 0x97, 0xA2, 0xE0, 0xA9, 0x50, 0x94, 0x5A, 0x90, 0x9A,
        0x58, 0xA2, 0x83, 0x83, 0x56, 0x28, 0xC9, 0x57, 0xC8, 0x4D,
        0xCC, 0x4E, 0x05, 0x1A, 0x90, 0x8A, 0xA2, 0xB9, 0x3C, 0xBF,
        0x28, 0x5B, 0x0F, 0x00,
        // ADLER-32 checksum of uncompressed data
        0xEF, 0x1F, 0x23, 0xC4
    };
    uint8_t testFastCompressed[70] = {0};

    if(!dsReadZlibPtr(fastCompressed, testFastCompressed))
    {
        PD_FAIL("dsReadZlibPtr: could not read string with fast compression.");
        ++failed;
    }
    else
    {
        PD_SUCCESS("passed dsReadZlibPtr with fast compression.");
    }

    return failed;
}
